#!/usr/bin/env python3
"""Render the Bahamas override from pinned Natural Earth geographic coordinates."""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
feature = json.loads((ROOT / 'data/shape-overrides/bs.geojson').read_text())
polygons = feature['geometry']['coordinates']
points = [point for polygon in polygons for ring in polygon for point in ring]
# Local equirectangular projection, north up. Scale longitude at the central
# latitude so the islands retain their proportions and geographic spacing.
latitude = (min(p[1] for p in points) + max(p[1] for p in points)) / 2
longitude_scale = math.cos(math.radians(latitude))

def project(point):
    return point[0] * longitude_scale, -point[1]

projected = [project(point) for point in points]
min_x, min_y = map(min, zip(*projected))
max_x, max_y = map(max, zip(*projected))
scale = 960 / max(max_x - min_x, max_y - min_y)
center_x, center_y = (min_x + max_x) / 2, (min_y + max_y) / 2

def svg_point(point):
    x, y = project(point)
    return f'{512 + (x - center_x) * scale:.2f},{512 + (y - center_y) * scale:.2f}'

paths = []
for polygon in polygons:
    rings = ['M' + ' L'.join(svg_point(point) for point in ring) + ' Z' for ring in polygon]
    paths.append('  <path d="' + ' '.join(rings) + '"/>')
svg = '\n'.join([
    '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">',
    '  <!-- Natural Earth 1:10m Admin 0 Countries, v5.1.2 repository; public domain.',
    '       Generated by scripts/generate_bahamas_shape.py. -->',
    '<g fill="#000000" fill-rule="evenodd">',
    *paths,
    '</g>',
    '</svg>',
    '',
])
for region in ('all', 'namerica'):
    destination = ROOT / f'country-shapes/{region}/bs/vector.svg'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(svg)
print(f'Generated Bahamas outline: {len(polygons)} island polygons')
